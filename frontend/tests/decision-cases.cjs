// Real HTTP + PostgreSQL integration; run tests/case_browser_server.py first.
const {chromium}=require('playwright'),assert=require('node:assert/strict')
const API=process.env.URBIA_BROWSER_API||'http://127.0.0.1:8773'
const BASE=process.env.URBIA_BROWSER_URL||'http://127.0.0.1:4175'
;(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true})
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Sao_Paulo'})
  const email=`browser-${Date.now()}@test.local`,password='disposable-browser-password'
  let response=await context.request.post(API+'/api/auth/register',{data:{name:'Parceiro de teste',email,password,profile:'incorporadora'}})
  assert.equal(response.status(),200)
  const token=(await (await context.request.post(API+'/api/auth/login',{data:{email,password}})).json()).access_token
  const headers={Authorization:'Bearer '+token}
  await context.addInitScript(token=>localStorage.setItem('token',token),token)
  const page=await context.newPage(),errors=[]
  page.on('pageerror',e=>{errors.push(e.message);console.error('Browser error:',e.message)})
  await context.route('**/api/**',async route=>{
   const req=route.request(),url=new URL(req.url())
   if(url.pathname.includes('geojson'))return route.fulfill({contentType:'application/json',body:JSON.stringify({type:'FeatureCollection',features:[]})})
   const requestHeaders={...req.headers()};delete requestHeaders.host;delete requestHeaders['content-length']
   const result=await context.request.fetch(API+url.pathname+url.search,{method:req.method(),headers:requestHeaders,data:req.postData()||undefined})
   await route.fulfill({response:result})
  })
  await page.goto(BASE+'/app')
  const journeys=[['incorporadora','incorpora','Comparar propostas'],['construtora','obras','Preparar investigação'],['investidor','invest','Comparar investimentos'],['corretor','mercado','Apresentar imóvel'],['empreendedor','negocios','Comparar pontos'],['governo','governo','Priorizar visitas']]
  for(const [profile,kind,action] of journeys){
   await page.setViewportSize({width:1440,height:1000})
   await page.getByLabel('Modo de trabalho').selectOption(profile)
   await page.getByRole('button',{name:action,exact:true}).waitFor()
   await page.getByRole('button',{name:action,exact:true}).click()
   await page.getByLabel('Nome da análise',{exact:true}).fill('Teste de navegação')
   await page.getByRole('button',{name:'Próxima etapa',exact:true}).focus()
   await page.keyboard.press('Enter')
   await page.getByRole('group',{name:'Informações específicas da sua decisão',exact:true}).waitFor()
   const createdResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/case-demos/'+kind)
   page.once('dialog',dialog=>dialog.accept())
   await page.getByRole('button',{name:'Conhecer exemplo demonstrativo',exact:true}).click()
   const saved=await (await createdResponse).json()
   assert.equal(saved.kind,kind)
   await page.locator(`.decision-case[data-case-id="${saved.id}"][data-kind="${kind}"]`).waitFor()
   await page.getByRole('status').filter({hasText:'Demonstração isolada.'}).waitFor()
   await page.getByLabel('Síntese da decisão',{exact:true}).waitFor()
   await page.getByRole('button',{name:'2. Informações essenciais',exact:true}).click()
   console.log('Editing journey:',kind)
   if(kind==='incorpora')await page.getByRole('group',{name:'Proposta 1',exact:true}).getByLabel('Aquisição do terreno (R$)',{exact:true}).fill('0')
   if(kind==='obras')await page.getByLabel('Objetivo e observações da investigação',{exact:true}).fill('Preparar vistoria com responsável técnico — exemplo editado.')
   if(kind==='invest')await page.getByLabel('Orçamento disponível (R$)',{exact:true}).fill('0')
   if(kind==='mercado')await page.getByLabel('Perguntas ao proprietário',{exact:true}).fill('Confirmar documentação antes da apresentação.')
   if(kind==='negocios')await page.getByRole('group',{name:'Ponto 1',exact:true}).getByLabel('Aluguel mensal (R$)',{exact:true}).fill('0')
   if(kind==='governo')await page.getByLabel('Por que investigar esta região?',{exact:true}).fill('Confirmar oferta pública e capacidade em vistoria — simulação.')
   await page.getByRole('button',{name:'Salvar análise',exact:true}).click()
   await page.getByRole('status').filter({hasText:'Análise salva'}).waitFor()
   await page.reload()
   await page.getByRole('button',{name:'Minhas análises',exact:true}).click()
   await page.getByRole('button',{name:'Exemplos salvos',exact:true}).click()
   await page.getByRole('button',{name:'Abrir análise: '+saved.title,exact:true}).click()
   await page.getByRole('status').filter({hasText:'Análise reaberta'}).waitFor()
   await page.getByRole('button',{name:'3. Confira os dados',exact:true}).click()
   await page.getByRole('button',{name:action,exact:true}).click()
   await page.getByLabel('Síntese da decisão',{exact:true}).waitFor()
   await page.getByRole('button',{name:'Editar tarefa',exact:true}).first().click()
   await page.getByLabel('Responsável',{exact:true}).fill('Equipe de investigação')
   await page.getByLabel('Prazo da tarefa',{exact:true}).fill('2030-01-15')
   await page.getByLabel('Andamento',{exact:true}).selectOption('done')
   await page.getByLabel('Evidência para conclusão',{exact:true}).fill('Referência de conferência registrada para teste; não é aprovação real.')
   await page.getByRole('button',{name:'Salvar tarefa',exact:true}).click()
   await page.getByRole('status').filter({hasText:'Tarefa salva com evidência e histórico'}).waitFor()
   const popup=page.waitForEvent('popup')
   await page.getByRole('button',{name:'Abrir relatório para PDF',exact:true}).click()
   const report=await popup
   await report.getByRole('heading',{name:'O que encontramos',exact:true}).waitFor()
   assert.ok((await report.locator('body').innerText()).includes('SIMULAÇÃO DEMONSTRATIVA'))
   await report.pdf({path:`/private/tmp/urbia-${kind}-executivo.pdf`,format:'A4',printBackground:true})
   await report.close()
   await page.setViewportSize({width:390,height:844})
   await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=0)
   await page.getByLabel('Síntese da decisão',{exact:true}).scrollIntoViewIfNeeded()
   await page.screenshot({path:`/private/tmp/urbia-${kind}-guided-mobile.png`})
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),kind+' mobile overflow')
   assert.ok(await page.evaluate(()=>document.querySelector('.case-executive').getBoundingClientRect().right<=window.innerWidth),kind+' executive panel overflow')
   const current=await (await context.request.get(API+`/api/cases/${saved.id}`,{headers})).json()
   assert.equal(current.tasks[0].status,'done')
   if(kind==='incorpora')assert.equal(current.inputs.proposals[0].financial.land_cost,0)
   if(kind==='invest')assert.equal(current.inputs.budget,0)
   if(kind==='negocios')assert.equal(current.inputs.points[0].rent,0)
   console.log('Validated real save/reopen/analyze/tasks/print/mobile:',kind)
  }
  await page.getByText('Registrar o que ficou claro ou precisa melhorar',{exact:true}).click()
  await page.getByLabel('Observação sobre a análise',{exact:true}).fill('Quero conferir a capacidade antes de discutir novas vagas.')
  await page.getByRole('button',{name:'Registrar observação',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Observação registrada no caso'}).waitFor()
  await page.getByRole('button',{name:'Usaria em um caso próprio',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Interesse registrado nesta demonstração'}).waitFor()
  const real=await (await context.request.post(API+'/api/cases',{headers,data:{title:'Caso real sem cobertura',kind:'invest',city_ibge:'3550308',inputs:{budget:0}}})).json()
  const analyzed=await (await context.request.post(API+`/api/cases/${real.id}/analyze`,{headers,data:{revision:real.revision}})).json()
  assert.ok(analyzed.result.summary.gaps.some(x=>x.includes('sem cobertura')))
  assert.equal((await context.request.post(API+`/api/cases/${real.id}/reset-demo`,{headers,data:{revision:analyzed.revision}})).status(),409)
  assert.deepEqual(errors,[])
  console.log('Validated unknown-city handling and real/demo isolation. Six PDF artifacts generated.')
  await context.close()
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
