// Docker/API are real; the scores response is empty to exercise missing-data navigation.
const {chromium}=require('playwright'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const BASE=process.env.URBIA_PRESENTATION_URL||'http://127.0.0.1:18088'
;(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true})
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}})
  assert.equal((await context.request.get(BASE+'/api/readiness')).status(),200)
  const email=`navigation-${Date.now()}@test.local`,password=crypto.randomBytes(20).toString('hex')
  assert.equal((await context.request.post(BASE+'/api/auth/register',{data:{name:'Teste de navegação',email,password,profile:'incorporadora'}})).status(),200)
  const token=(await(await context.request.post(BASE+'/api/auth/login',{data:{email,password}})).json()).access_token
  await context.addInitScript(token=>localStorage.setItem('token',token),token)
  const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.route('**/api/scores',route=>route.fulfill({contentType:'application/json',body:'[]'}))
  await page.goto(BASE+'/app');await page.getByRole('button',{name:'Comparar propostas',exact:true}).click()
  await page.getByRole('button',{name:'Minhas análises',exact:true}).click();await page.getByRole('heading',{name:'Minhas análises',exact:true}).waitFor()
  await page.getByRole('button',{name:'Nova análise',exact:true}).click();await page.getByRole('button',{name:'Começar em Urbia Invest',exact:true}).click()
  await page.getByLabel('Nome da análise',{exact:true}).fill('Rascunho que não pode sumir')
  page.once('dialog',dialog=>dialog.dismiss());await page.getByRole('button',{name:'Minhas análises',exact:true}).click()
  assert.equal(await page.getByLabel('Nome da análise',{exact:true}).inputValue(),'Rascunho que não pode sumir')
  page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'Minhas análises',exact:true}).click()
  await page.getByRole('heading',{name:'Minhas análises',exact:true}).waitFor()
  console.log('PASS: same-menu click returns to library and preserves drafts when discard is canceled')
  await page.locator('.sidebar-extra-tools > summary').click()
  assert.equal(await page.getByRole('button',{name:'Confirmar no mapa',exact:true}).isEnabled(),true)
  await page.getByRole('button',{name:'Confirmar no mapa',exact:true}).click()
  await page.getByRole('heading',{name:'Os dados desta ferramenta ainda não estão disponíveis',exact:true}).waitFor()
  await page.getByRole('button',{name:'Ir para minhas análises',exact:true}).click();await page.getByRole('heading',{name:'Minhas análises',exact:true}).waitFor()
  console.log('PASS: tools with missing data explain the limitation and provide a working return path')
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'Abrir menu',exact:true}).click();await page.getByRole('button',{name:'Início',exact:true}).click()
  await page.getByRole('button',{name:'Comparar propostas',exact:true}).click()
  await page.getByRole('button',{name:'Abrir menu',exact:true}).click();await page.getByRole('button',{name:'Minhas análises',exact:true}).click()
  await page.getByRole('heading',{name:'Minhas análises',exact:true}).waitFor()
  await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=0)
  assert.deepEqual(errors,[])
  console.log('PASS: mobile menu opens, navigates and closes; no JavaScript errors')
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
